    EXIT_NO_PROGRESS = "EXIT_NO_PROGRESS"
    EXIT_TIME = "EXIT_TIME"
    EXIT_FAILURE = "EXIT_FAILURE"
    EXIT_LONG_WATCH = "EXIT_LONG_WATCH"
    EXIT_SHORT_WATCH = "EXIT_SHORT_WATCH"
    EXIT_AND_REVERSE_LONG = "EXIT_AND_REVERSE_LONG"
