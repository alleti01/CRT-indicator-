    ENTRY_CHECK_SHORT = "ENTRY_CHECK_SHORT"
    WAIT_LONG = "WAIT_LONG"
    WAIT_SHORT = "WAIT_SHORT"
    LONG_ACTIVE = "LONG_ACTIVE"
    SHORT_ACTIVE = "SHORT_ACTIVE"
    LONG_WARNING = "LONG_WARNING"
    SHORT_WARNING = "SHORT_WARNING"
    REVERSAL_WATCH_LONG = "REVERSAL_WATCH_LONG"
    REVERSAL_WATCH_SHORT = "REVERSAL_WATCH_SHORT"
    EXIT_PENDING = "EXIT_PENDING"
    REVERSAL_PENDING = "REVERSAL_PENDING"
    ERROR = "ERROR"
    HALTED = "HALTED"


